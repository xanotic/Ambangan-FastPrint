-- =====================================================================
--  AMBANGAN FAST PRINT  -  Oracle schema + seed data (consolidated)
--  Source: "Create Table AMBANGANFASTPRINT SCHEMA.txt"
--        + "INHERITANCEAMBANGANFASTPRINT.txt"
--  Target: Oracle XE 21c (gvenzl/oracle-xe), schema AMBANGANFASTPRINT
--
--  Notes:
--   * SET DEFINE OFF  -> stops SQL*Plus treating '&' (e.g. 'Banner&Bunting')
--     as a substitution variable, which would otherwise prompt / hang.
--   * Drop block up top makes the script safely re-runnable.
--   * Circular FK (ORDERS<->RECEIPT) is added AFTER both tables exist.
--   * Inheritance/subtype rows are inserted after SERVICE is populated.
-- =====================================================================

SET DEFINE OFF;
WHENEVER SQLERROR CONTINUE;

-- ---------- clean slate (ignore "table does not exist") ----------
BEGIN
  FOR t IN (
    SELECT table_name FROM user_tables
    WHERE table_name IN (
      'DELIVERY','ORDERSERVICE','RECEIPT','ORDERS','MACHINE',
      'BANNERANDBUNTING','NAMETAG','RUBBERSTAMP','BUSINESSCARD','PRINT',
      'SERVICE','EMPLOYEE','CUSTOMER')
  ) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
  END LOOP;
END;
/

WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;

-- =====================================================================
--  TABLES
