--CUSTOMER
create table CUSTOMER(
    CustomerID number generated by default as identity (start with 1 increment by 1),
    CustomerName varchar2(100) not null,
    CustomerPhoneNum varchar2(20),
    CustomerEmail varchar2(120),                 -- added: website identifies customers by email
    constraint Customer_CustomerID_PK primary key (CustomerID)
);

--EMPLOYEE
create table EMPLOYEE(
    EmployeeID number generated by default as identity (start with 1 increment by 1),
    EmployeeName varchar2(100) not null,
    EmployeePhone varchar2(20),
    EmployeeJobPosition varchar2(50),
    constraint Employee_EmployeeID_PK primary key (EmployeeID)
);

--SERVICE
create table SERVICE(
    ServiceID number generated by default as identity (start with 51 increment by 1),
    ServiceType varchar2(100) not null,
    ServicePrice number(10,2) check(ServicePrice>0),
    ServiceDesignPicture varchar2(255),
    constraint Service_ServiceID_PK primary key (ServiceID)
);

-- PRINT
CREATE TABLE PRINT(
    ServiceID NUMBER,
    PDocumentName VARCHAR2(100),
    PSelectedPage NUMBER,
    PaperType VARCHAR2(50),
    PColourType VARCHAR2(50),
    CONSTRAINT Print_ServiceID_PK PRIMARY KEY (ServiceID),
    CONSTRAINT Print_ServiceID_FK FOREIGN KEY (ServiceID)
        REFERENCES SERVICE(ServiceID)
);

-- BUSINESSCARD
CREATE TABLE BUSINESSCARD(
    ServiceID NUMBER,
    BSDoubleSided VARCHAR2(5) CHECK (BSDoubleSided IN ('Yes','No')),
    BSCardThickness NUMBER(10,2) CHECK (BSCardThickness IN (0.35, 0.40, 0.80)),
    BSCornerStyle VARCHAR2(50) CHECK (BSCornerStyle IN ('Round','Square')),
    CONSTRAINT BusinessCard_ServiceID_PK PRIMARY KEY (ServiceID),
    CONSTRAINT BusinessCard_ServiceID_FK FOREIGN KEY (ServiceID)
        REFERENCES SERVICE(ServiceID)
);

-- RUBBERSTAMP
CREATE TABLE RUBBERSTAMP(
    ServiceID NUMBER,
    RSStampType VARCHAR2(50) CHECK (RSStampType IN ('Self-Inking','Pre-Inked','Traditional','Company Stamp')),
    RSKeychain VARCHAR2(5),
    RSInkColour VARCHAR2(50),
    RSCover VARCHAR2(50),
    RSTextAlignment VARCHAR2(50),
    CONSTRAINT RubberStamp_ServiceID_PK PRIMARY KEY (ServiceID),
    CONSTRAINT RubberStamp_ServiceID_FK FOREIGN KEY (ServiceID)
        REFERENCES SERVICE(ServiceID)
);

-- NAMETAG
CREATE TABLE NAMETAG(
    ServiceID NUMBER,
    NTMaterial VARCHAR2(50),
    NTLogo VARCHAR2(255),
    NTColor VARCHAR2(50),
    NTAttachmentType VARCHAR2(50),
    CONSTRAINT NameTag_ServiceID_PK PRIMARY KEY (ServiceID),
    CONSTRAINT NameTag_ServiceID_FK FOREIGN KEY (ServiceID)
        REFERENCES SERVICE(ServiceID)
);

-- BANNERANDBUNTING
CREATE TABLE BANNERANDBUNTING(
    ServiceID NUMBER,
    PickOrientation VARCHAR2(50) CHECK (PickOrientation IN ('Horizontal','Vertical')),
    CONSTRAINT BannerAndBunting_ServiceID_PK PRIMARY KEY (ServiceID),
    CONSTRAINT BannerAndBunting_ServiceID_FK FOREIGN KEY (ServiceID)
        REFERENCES SERVICE(ServiceID)
);

--MACHINE
create table MACHINE(
    MachineID number generated by default as identity (start with 34 increment by 1),
    MachineName varchar2(100) not null,
    MachineType varchar2(80) not null,
    MachineBrand varchar2(80) not null,
    MachineStatus varchar2(30) CHECK(MachineStatus in('Active','Maintenance')),
    constraint Machine_MachineID_PK primary key (MachineID)
);

--ORDERS
create table ORDERS(
    OrderID number generated by default as identity (start with 1 increment by 1),
    OrderDateTime date not null,
    EmployeeID number not null,
    ReceiptID number,
    CustomerID number not null,
    Remark varchar2(255),
    OrderStatus varchar2(20) default 'Pending'   -- added: dashboard order lifecycle
        check (OrderStatus in ('Pending','Ready to Pick Up','Completed','Cancelled')),
    constraint Orders_OrderID_PK primary key (OrderID),
    constraint Orders_EmployeeID_FK foreign key (EmployeeID) references EMPLOYEE(EmployeeID),
    constraint Orders_CustomerID_FK foreign key (CustomerID) references CUSTOMER(CustomerID)
);

--ORDERSERVICE
create table ORDERSERVICE(
    ServiceID number not null,
    OrderID number not null,
    Quantity number check(quantity>0),
    OSSize varchar2(50),
    Text varchar2(500),
    AmountPrice number(10,2),
    MachineID number,
    constraint OrderService_PK primary key (ServiceID, OrderID),
    constraint OrderService_ServiceID_FK foreign key (ServiceID) references SERVICE(ServiceID),
    constraint OrderService_OrderID_FK foreign key (OrderID) references ORDERS(OrderID),
    constraint OrderService_MachineID_FK foreign key (MachineID) references MACHINE(MachineID)
);

--RECEIPT
create table RECEIPT(
    ReceiptID number generated by default as identity (start with 1 increment by 1),
    ReceiptDate date DEFAULT SYSDATE,
    PaymentMethod varchar2(50) not null CHECK (PaymentMethod IN ('Cash','Card','Online')),
    EmployeeID number not null,
    OrderID number,
    ReceiptDepoAmount number(10,2),
    ReceiptTotalAmount number(10,2) check (ReceiptTotalAmount>0),
    constraint Receipt_ReceiptID_PK primary key (ReceiptID),
    constraint Receipt_EmployeeID_FK foreign key (EmployeeID) references EMPLOYEE(EmployeeID)
);

--DELIVERY
create table DELIVERY(
    DeliveryID number generated by default as identity (start with 1 increment by 1),
    DeliveryDate date default sysdate,
    DeliveryAddress varchar2(255) not null,
    DeliveryRemark varchar2(255),
    OrderID number unique,
    TrackingNumber varchar2(100),
    constraint Delivery_DeliveryID_PK primary key (DeliveryID),
    constraint Delivery_OrderID_FK foreign key (OrderID) references ORDERS(OrderID)
);

--CIRCULAR FOREIGN KEYS
alter table ORDERS
add constraint Orders_ReceiptID_FK
foreign key (ReceiptID)
references RECEIPT(ReceiptID);

alter table RECEIPT
add constraint Receipt_OrderID_FK
foreign key (OrderID)
references ORDERS(OrderID);

